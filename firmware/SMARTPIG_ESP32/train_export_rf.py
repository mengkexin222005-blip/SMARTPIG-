"""SMARTPIG - train the Random Forest Regressor and export it to Arduino headers.

Run:   pip install pandas numpy scikit-learn micromlgen
       python train_export_rf.py
Output (copy all .h files next to SMARTPIG_ESP32.ino):
  RandomForestRegressor.h   the trained forest
  rf_test_vectors.h         test inputs + Python's answers, used by the 'rftest' serial command
  rf_test_vectors.csv       the same table, readable in Excel

The 12 features MUST stay in this exact order (same as x[0..11] in the sketch).
The model is trained on ALL pig counts (1, 2 and 3); Pig_count is the last input.
"""
import numpy as np
import pandas as pd
from micromlgen import port
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error
from sklearn.model_selection import GroupKFold, cross_val_predict

FEATURES = ["Age_days", "Stage_code", "Meal_ratio", "Temperature_C", "Humidity_percent",
            "Daily_feed_per_pig_g", "Feed_adjust_percent", "Meal_target_g",
            "Empty_meals_last_10", "Leftover_meals_last_10", "Tray_Load_G",
            "Pig_count"]
TARGET = "Dispense_G"
N_REAL_PER_PIG_COUNT = 8      # test rows taken from the dataset, per pig count
N_SYNTHETIC = 12              # extra random test rows inside the feature ranges

df = pd.read_csv("SMARTPIG_8_Adaptive_Dataset.csv")
X, y = df[FEATURES], df[TARGET]
print("Training rows: %d  (pig counts: %s)" % (len(df), [int(p) for p in sorted(df["Pig_count"].unique())]))

model = RandomForestRegressor(n_estimators=10, max_depth=6, min_samples_leaf=10, random_state=42)

# Honest accuracy check: every fold holds out whole ages the model never saw.
pred = cross_val_predict(model, X, y, groups=df["Age_days"], cv=GroupKFold(n_splits=5)).clip(0)
rule = (df["Meal_target_g"] - df["Tray_Load_G"]).clip(lower=0)
print("Random forest MAE: %.1f g   | exact rule MAE: %.1f g" % (mean_absolute_error(y, pred), mean_absolute_error(y, rule)))
for p in sorted(df["Pig_count"].unique()):
    m = (df["Pig_count"] == p).values
    print("   %d pig(s): forest MAE %.1f g | rule MAE %.1f g" % (p, mean_absolute_error(y[m], pred[m]), mean_absolute_error(y[m], rule[m])))

model.fit(X, y)
code = port(model)
open("RandomForestRegressor.h", "w").write(code)
print("Wrote RandomForestRegressor.h (%d KB)" % (len(code) // 1024))

# ---------------------------------------------------------------------------
# Test values: inputs + what Python predicts, so the ESP32 can be checked.
# ---------------------------------------------------------------------------
rng = np.random.RandomState(7)
real = df.groupby("Pig_count", group_keys=False).sample(N_REAL_PER_PIG_COUNT, random_state=7)[FEATURES]

lo, hi = X.min(), X.max()
syn = pd.DataFrame({c: rng.uniform(lo[c], hi[c], N_SYNTHETIC) for c in FEATURES})
syn["Age_days"] = rng.randint(int(lo["Age_days"]), int(hi["Age_days"]) + 1, N_SYNTHETIC)
syn["Stage_code"] = pd.cut(syn["Age_days"], [0, 50, 80, 115, 999], labels=[1, 2, 3, 4]).astype(int)
syn["Pig_count"] = rng.randint(1, 4, N_SYNTHETIC)
for c in ["Empty_meals_last_10", "Leftover_meals_last_10"]:
    syn[c] = syn[c].round()

tests = pd.concat([real, syn], ignore_index=True).astype(np.float32)   # the ESP32 works in float32
tests["Python_prediction_g"] = model.predict(tests[FEATURES])    # raw, before any clipping
tests["Source"] = ["dataset"] * len(real) + ["synthetic"] * len(syn)
tests.to_csv("rf_test_vectors.csv", index=False, float_format="%.9g")

def cf(v, fmt):                      # C float literal: always has a '.' or exponent, then 'f'
    t = fmt % v
    return (t if any(ch in t for ch in ".eE") else t + ".0") + "f"

rows = ",\n".join("  {" + ", ".join(cf(v, "%.9g") for v in r) + "}" for r in tests[FEATURES].values)
exp = ", ".join(cf(v, "%.6f") for v in tests["Python_prediction_g"])
with open("rf_test_vectors.h", "w") as f:
    f.write("#pragma once\n// Generated by train_export_rf.py - do not edit.\n")
    f.write("// Feature order: " + ", ".join(FEATURES) + "\n")
    f.write("#define RF_TEST_N %d\n#define RF_TEST_FEATURES %d\n" % (len(tests), len(FEATURES)))
    f.write("const float RF_TEST_X[RF_TEST_N][RF_TEST_FEATURES] = {\n%s\n};\n" % rows)
    f.write("const float RF_TEST_Y[RF_TEST_N] = {%s};   // model.predict() in Python\n" % exp)
print("Wrote rf_test_vectors.h and rf_test_vectors.csv (%d test rows)" % len(tests))
